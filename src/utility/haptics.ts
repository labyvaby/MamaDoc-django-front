/**
 * Тактильный отклик на действия, которые меняют данные.
 *
 * Зачем: регистратура работает с телефоном в руке и часто не смотрит на экран в
 * момент нажатия («пациент здесь» на ходу, оплата под диктовку). Короткая
 * вибрация подтверждает, что действие ушло, раньше, чем прилетит ответ бэка.
 *
 * Где уже применялось: сканер склада (`src/pages/inventory/django/index.tsx`)
 * вибрировал напрямую через navigator.vibrate — здесь тот же приём, но одной
 * точкой, чтобы длительности не разъезжались по экранам.
 *
 * Ограничения (сознательные, не баг):
 *  • iOS Safari Vibration API не поддерживает — там вызовы просто ничего не
 *    делают, никакого фолбэка не изображаем;
 *  • на десктопе API есть, но железа нет — вызов безвреден;
 *  • вибрация не заменяет тост: это дополнительный канал, а не единственный.
 */

const vibrate = (pattern: number | number[]): void => {
  try {
    navigator.vibrate?.(pattern);
  } catch {
    // Политика браузера (нет жеста пользователя, экономия батареи) — не повод
    // ронять обработчик действия.
  }
};

/** Обычное действие: смена статуса, отметка, подтверждение. */
export const hapticTap = (): void => vibrate(12);

/** Успех с деньгами или завершением: оплата, закрытие чека. */
export const hapticSuccess = (): void => vibrate([12, 45, 20]);
