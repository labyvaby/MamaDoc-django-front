import type { Gender } from "./types";

/** «пациент» → «Пациент». Первая буква, остальное не трогаем. */
export const capitalize = (value: string): string =>
  value ? value.charAt(0).toUpperCase() + value.slice(1) : value;

/** «Пациент» → «пациент». Для середины предложения. */
export const lower = (value: string): string =>
  value ? value.charAt(0).toLowerCase() + value.slice(1) : value;

/**
 * Согласование по роду для случаев, где безличную формулировку не подобрать:
 *   agree(glossary.patient.gender, ["добавлен", "добавлена", "добавлено"])
 *
 * По возможности этого стоит избегать — предпочитайте формулировки, не
 * зависящие от рода термина («Запись создана» вместо «Пациент добавлен»).
 * См. docs/i18n-verticals.md, раздел «Род термина».
 * Тот же выбор формы, но для JSON-шаблонов — форматтер `genderForm` ниже.
 */
export const agree = (gender: Gender, [m, f, n]: [string, string, string]): string => {
  if (gender === "f") return f;
  if (gender === "n") return n;
  return m;
};

/**
 * Форма слова по роду термина — форматтер i18next для JSON-шаблонов:
 *   {{<term>.gender, gender(m: создан; f: создана; n: создано)}}
 *
 * Ключи параметров — ЛАТИНСКИЕ «m», «f», «n» (ровно как род в TermForms.gender),
 * значения — целые слова целиком, а не голое окончание: пишите
 * `gender(m: создан; f: создана)`, а не пытайтесь передать одно только
 * окончание («н» / «на») — genderForm() выбирает одну из готовых строк, а не
 * клеит окончание к общему корню.
 *
 * Разделители — те же, что у самого i18next: «;» отделяет параметры друг от
 * друга, «:» отделяет ключ формы от значения, и разбирает их форматтер
 * i18next ДО вызова этой функции. Поэтому внутри формы нельзя использовать
 * «;», «(» и «)»: i18next режет по ним ещё при разборе параметров, и это
 * портит формы, а не просто попадает в текст — например, случайная «(»
 * стирает все формы разом (каждый род получает один и тот же обрезанный
 * кусок текущей формы вместо своего слова). Отсутствующая форма, незнакомый
 * род или пустая строка — мужская форма (как было в шаблонах до этого
 * форматтера).
 *
 * ВНИМАНИЕ: i18next мёрджит переменные вызова t(key, vars) поверх параметров
 * форматтера, а не наоборот, — если у ключа уже есть переменная с именем
 * ровно «m», «f» или «n», она молча подменит собой форму рода. Пример
 * реального риска: `appointments:conclusionSlots.documentN` зовёт
 * t(key, { n: 2 }) — этому ключу нельзя добавлять `gender(...)`, имя «n» уже
 * занято номером документа.
 *
 * JS-копия этой функции живёт в scripts/i18n-check.mjs (проверка терминологии
 * рендерит шаблоны своим экземпляром i18next) — правите одну, правьте и другую.
 */
export const genderForm = (value: unknown, forms: Record<string, unknown>): string => {
  const pick = (g: string): string => (typeof forms[g] === "string" ? (forms[g] as string) : "");
  const gender = value === "f" || value === "n" ? value : "m";
  return pick(gender) || pick("m");
};
