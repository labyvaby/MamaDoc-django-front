import { describe, expect, it } from "vitest";

import { parseNotice, splitLisBullets } from "./labTestCardText";

describe("splitLisBullets", () => {
  it("режет склеенные через « - » пункты на список", () => {
    const text =
      "- Скрининговые обследования в рамках наблюдения - базовые обследования при госпитализации - диагностика анемий";
    expect(splitLisBullets(text)).toEqual([
      "Скрининговые обследования в рамках наблюдения",
      "базовые обследования при госпитализации",
      "диагностика анемий",
    ]);
  });

  it("дефис внутри слова пунктом не считает", () => {
    expect(splitLisBullets("Ср. кон-ия гемоглобина в эритроците")).toEqual([
      "Ср. кон-ия гемоглобина в эритроците",
    ]);
  });

  it("тире внутри фразы не режет пункт", () => {
    expect(
      splitLisBullets("- Натощак - не менее 8 часов (желательно — не менее 12). Кофе — нельзя."),
    ).toEqual([
      "Натощак",
      "не менее 8 часов (желательно — не менее 12). Кофе — нельзя.",
    ]);
  });

  it("один пункт — не список", () => {
    expect(splitLisBullets("- Только одно показание")).toEqual([
      "Только одно показание",
    ]);
  });
});

describe("parseNotice", () => {
  it("отделяет код и периодичность от перечня показателей", () => {
    const notice =
      "Код: 1.2 Ежедн. *Гемоглобин (HGB), Эритроциты (RBC), Цв. показатель (MCHC), Тромбоциты (PLT).";
    expect(parseNotice(notice)).toEqual({
      meta: "Код: 1.2 Ежедн.",
      analytes: [
        "Гемоглобин (HGB)",
        "Эритроциты (RBC)",
        "Цв. показатель (MCHC)",
        "Тромбоциты (PLT)",
      ],
      rest: "",
    });
  });

  it("без звёздочки отдаёт текст как есть", () => {
    expect(parseNotice("Сдавать до 10:00")).toEqual({
      meta: "",
      analytes: [],
      rest: "Сдавать до 10:00",
    });
  });

  it("звёздочка без перечня показателей — не состав", () => {
    expect(parseNotice("Код: 7 *срочно, до обеда")).toEqual({
      meta: "",
      analytes: [],
      rest: "Код: 7 *срочно, до обеда",
    });
  });
});
