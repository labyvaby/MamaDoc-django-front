import type React from "react";

/**
 * Общие типы канбан-доски.
 *
 * Ядро отвечает за раскладку, перетаскивание и вид карточки; что показывать
 * внутри карточки и какие переносы разрешены — дело модуля (задачи, воронка
 * продаж). Данные ядро не грузит: у задач это запрос на колонку, у сделок —
 * один агрегат на доску, общий слой данных тут был бы натяжкой.
 */

/** Колонка доски: статус задачи, этап воронки — что угодно с устойчивым ключом. */
export type BoardColumnId = string | number;

export interface BoardColumnDef<C extends BoardColumnId> {
  id: C;
  title: string;
  /** Цвет точки в шапке — тот же, что у чипа статуса в списке. */
  dotColor?: string;
  /** Счётчик колонки: всего элементов, а не только загруженных. */
  count?: number;
  /** Что показать в шапке справа от счётчика — например сумма сделок. */
  headerMeta?: React.ReactNode;
  /** Колонка грузится: вместо карточек — скелетоны. */
  loading?: boolean;
  /** Подпись пустой колонки («Нет задач»). */
  emptyHint?: string;
  /** Хвост колонки: «Прокрутите, чтобы загрузить ещё 20». */
  footer?: React.ReactNode;
  /** Прокрутка подошла к концу — модуль догружает следующую порцию. */
  onScrollEnd?: () => void;
}

export interface BoardCardAction {
  /** Ключ пункта меню; он же ключ React-списка. */
  key: string;
  label: string;
  onSelect: () => void;
}

/**
 * Описание карточки: модуль отдаёт содержимое и оформление, ядро добавляет
 * перетаскивание, меню действий и анимацию появления.
 */
export interface BoardCardSpec {
  /** Что читает скринридер: «Задача: заказать шприцы». */
  ariaLabel: string;
  /** Цвет полоски по левому краю (null — без полоски). */
  accentColor?: string | null;
  accentTooltip?: string;
  /** Требует внимания (просроченный срок) — рамка меняет цвет. */
  alert?: boolean;
  /** Те же переходы, что и перетаскиванием: на тач-экране drag недоступен. */
  actions?: BoardCardAction[];
  /** Подпись кнопки меню действий. */
  actionsTooltip?: string;
  onOpen: () => void;
  content: React.ReactNode;
}
